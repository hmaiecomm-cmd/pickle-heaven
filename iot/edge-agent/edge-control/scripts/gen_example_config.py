"""Regenerates config/examples/circuits.yaml and cameras.yaml from the built-in catalogs (single source of truth)."""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from edge_control.config.loader import default_cameras, default_circuits  # noqa: E402

out = Path(__file__).resolve().parents[1] / "config" / "examples"
hdr = "# Generated by scripts/gen_example_config.py from the built-in catalog.\n"
circ = {"circuits": [c.model_dump(mode="json", exclude_none=False) for c in default_circuits()]}
(out / "circuits.yaml").write_text(
    hdr + "# Voltages/loads are planning data from 18powerlinelist.jpg, NOT measurements. null = unknown (never 0).\n"
    "# offline_policy 'unconfigured' means: the site must decide what a stale cloud cache should do.\n"
    + yaml.safe_dump(circ, allow_unicode=True, sort_keys=False), encoding="utf-8")
cams = {"nvr_id": "nvr-1", "cameras": [c.model_dump(mode="json") for c in default_cameras()]}
(out / "cameras.yaml").write_text(
    hdr + "# camera-01..06 are LOGICAL numbers. Real NVR channel / ISAPI track / SDK channel / RTSP stream ids are\n"
    "# NOT assumed: they are bound (null/unbound until then) in System > Deployment mapping > Cameras/NVR.\n"
    + yaml.safe_dump(cams, allow_unicode=True, sort_keys=False), encoding="utf-8")
print("ok")
