"""Exports contracts/openapi.yaml from the REAL FastAPI routes (never hand-edited)."""
import json
import os
import sys
import tempfile
from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "src"))
tmp = Path(tempfile.mkdtemp())
os.environ.update({
    "EDGE_AUTH_TOKENS": json.dumps([{"token": "export-only-token", "role": "viewer", "actor": "export"}]),
    "EDGE_CONFIG_DIR": str(root / "config" / "examples"), "EDGE_DATA_DIR": str(tmp / "data"),
    "EDGE_CACHE_DIR": str(tmp / "cache"), "EDGE_BACKGROUND_WORKERS": "false", "EDGE_MEDIA_BACKEND": "mock"})
from edge_control.api.app import create_app  # noqa: E402
from edge_control.config.settings import Settings  # noqa: E402

app = create_app(Settings(_env_file=None))
spec = app.openapi()
out = root / "contracts" / "openapi.yaml"
out.write_text("# Generated by scripts/export_openapi.py from the FastAPI routes. Do not edit by hand.\n"
               + yaml.safe_dump(json.loads(json.dumps(spec)), allow_unicode=True, sort_keys=False), encoding="utf-8")
print("wrote", out, "paths:", len(spec["paths"]))
